"""AI 위클리 → SoundCraft session script (session.txt): picture, narration, music, effects; voice chain,
music ducked by volume automation under every narration line, maximizer on the master.
Run: python3 make_session.py [--threshold DB]   then   soundcraft-cli script session.txt --save ai-week-1029.scraft --bounce mix.wav
Inputs: ../ai-week-1029.mp4 (picture), ../filmcraft/media/stem_vo.flac and stem_sfx.flac, media/stem_music_dry.flac (music before ducking),
media/vo_spans.json (the narration lines' start and end, from ../mix.py)."""
import argparse, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser(); ap.add_argument('--threshold', type=float, default=-3.8)   # maximizer threshold: sets the loudness (−3.8 → −14 LUFS)
a = ap.parse_args()
P = lambda *p: os.path.normpath(os.path.join(HERE, *p))
DUCK_DB, ATTACK, RELEASE = -7.0, 0.08, 0.15        # same depth and times as mix.py
spans = json.load(open(P('media/vo_spans.json')))
L = []
def cmd(i, **p): L.append(f'{i} {json.dumps(p, ensure_ascii=False)}')
cmd('session.new', name='AI 위클리 · Week 44', sample_rate=48000, bit_depth=24)
cmd('file.import_audio', paths=[P('../filmcraft/media/stem_vo.flac'), P('media/stem_music_dry.flac'), P('../filmcraft/media/stem_sfx.flac')], at={'seconds': 0})
for old, new in (('stem_vo', '내레이션'), ('stem_music_dry', '음악'), ('stem_sfx', '효과음')): cmd('track.rename', track=old, name=new)
cmd('file.import_video', path=P('../ai-week-1029.mp4'), at={'seconds': 0})
# the movie's own sound comes in as a track: keep it, muted, to compare against the original master
cmd('track.rename', track='ai-week-1029 audio', name='원본 믹스 (비교용)')
cmd('mix.mute', tracks=['원본 믹스 (비교용)'], value=True)
# narration: rumble out, a little presence, soft de-essing, gentle compression
cmd('mix.insert', track='내레이션', slot='a', plugin='eq_7band', params={'hpf_on': 1, 'hpf_freq': 90, 'hpf_slope': 2, 'low_mid_freq': 300, 'low_mid_gain': -2, 'high_mid_freq': 3500, 'high_mid_gain': 1.5})
cmd('mix.insert', track='내레이션', slot='b', plugin='de_esser', params={'freq': 6500, 'threshold': -32, 'range': 6})
cmd('mix.insert', track='내레이션', slot='c', plugin='compressor', params={'threshold': -20, 'ratio': 3, 'attack': 5, 'release': 80, 'knee': 6})
# music: leave room for the voice (the 1.2–5 kHz band), then duck it under every line with volume automation
cmd('mix.insert', track='음악', slot='a', plugin='eq_7band', params={'mid_freq': 2500, 'mid_gain': -3, 'mid_q': 0.7})
for s, e in spans:
    for t, v in ((s - ATTACK, 0.0), (s, DUCK_DB), (e, DUCK_DB), (e + RELEASE, 0.0)):
        cmd('automation.set_point', track='음악', param='volume', at={'seconds': round(max(t, 0), 3)}, value=v)
# master: a fader with the maximizer (−1.5 dB sample ceiling keeps true peak under −1 dBTP)
cmd('track.new', kind='master', format='stereo')
cmd('mix.insert', track='Master 1', slot='a', plugin='maximizer', params={'threshold': a.threshold, 'ceiling': -1.5, 'release': 50})
open(P('session.txt'), 'w', encoding='utf-8').write('# generated by make_session.py\n' + '\n'.join(L) + '\n')
print(len(L), 'commands →', P('session.txt'))
