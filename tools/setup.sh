#!/bin/sh
# @noah.aiart 영상 제작 스튜디오 — 도구 설치 (새 클라우드 세션이나 새 컴퓨터에서 한 번 실행)
#
#   sh tools/setup.sh            # 전부: lemo-opuscar + 샘플 음원 + Craft 앱 명령줄 도구 + 글꼴
#   sh tools/setup.sh lemo       # lemo-opuscar(코드로 그리는 영상 스타일)와 샘플 음원만
#   sh tools/setup.sh crafts     # Craft 앱 명령줄 도구만 (Rust 빌드, 앱 하나에 5~15분)
#   sh tools/setup.sh fonts      # 영상에 쓰는 OFL 글꼴만
#
# 설치 위치: $STUDIO_TOOLS (기본 ~/studio-tools). 끝나면 tools/env.sh 를 source 하면 경로가 잡힙니다.
# 필요한 것: git, curl, Node 20+, ffmpeg, Python 3.11+, Rust(cargo) — Craft 앱을 빌드할 때만.
set -e
T=${STUDIO_TOOLS:-$HOME/studio-tools}
mkdir -p "$T"
what=${1:-all}

clone() {   # clone or update a public repo into $T/<name>
  if [ -d "$T/$1/.git" ]; then git -C "$T/$1" pull -q --ff-only || true
  else GIT_LFS_SKIP_SMUDGE=1 git clone -q --depth 1 "https://github.com/$2/$1" "$T/$1"; fi
}

lemo() {
  clone lemo-opuscar lemomo-ai
  (cd "$T/lemo-opuscar" && sh plugin/skills/lemo-opuscar/scripts/setup.sh deps >/dev/null)
  for l in vsco2ce vcsl; do
    [ -d "$T/lemo-opuscar/core/audio/instruments/$l" ] || (cd "$T/lemo-opuscar" && sh tools/fetch.sh instruments $l)
  done
  echo "lemo-opuscar: $T/lemo-opuscar"
}

# Craft apps with a command-line tool (the desktop apps, ArtCraft and the launcher are installed on your own computer)
CRAFTS="filmcraft effectcraft soundcraft photocraft lightcraft vectorcraft designcraft deckcraft"
crafts() {
  clone craft-fonts storytold
  export CRAFT_FONTS_DIR="$T/craft-fonts"   # embeds the craft-fonts set (Korean included) into the apps' text engines
  for a in $CRAFTS; do
    clone $a storytold
    if [ -x "$T/$a/target/release/$a-cli" ]; then echo "$a-cli: already built"; continue; fi
    echo "building $a-cli…"
    (cd "$T/$a" && cargo build --release -q -p $a-cli) && echo "$a-cli: $T/$a/target/release/$a-cli" || echo "$a-cli: build FAILED (see cargo output above)"
  done
}

fonts() {   # the faces the films use (all SIL OFL), installed for the current user
  D=$HOME/.local/share/fonts; mkdir -p "$D"
  for f in barlowcondensed/BarlowCondensed-ExtraBold barlowcondensed/BarlowCondensed-SemiBold ibmplexmono/IBMPlexMono-Medium; do
    [ -s "$D/${f#*/}.ttf" ] || curl -fsSL -o "$D/${f#*/}.ttf" "https://raw.githubusercontent.com/google/fonts/main/ofl/$f.ttf"
  done
  command -v fc-cache >/dev/null && fc-cache -f >/dev/null 2>&1 || true
  echo "fonts: $D"
}

case $what in
  all) lemo; fonts; crafts ;;
  lemo) lemo ;;
  crafts) crafts ;;
  fonts) fonts ;;
  *) echo "usage: sh tools/setup.sh [all|lemo|crafts|fonts]"; exit 2 ;;
esac

cat > "$(dirname "$0")/env.sh" <<EOF
# generated by tools/setup.sh — source it: . tools/env.sh
export STUDIO_TOOLS="$T"
export LIB="$T/lemo-opuscar"
export CRAFT_FONTS_DIR="$T/craft-fonts"
for a in $CRAFTS; do [ -d "$T/\$a/target/release" ] && PATH="$T/\$a/target/release:\$PATH"; done
export PATH
EOF
echo "done. next: . tools/env.sh"
